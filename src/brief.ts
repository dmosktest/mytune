import {
  formatMemoryKb,
  formatSettingValue,
  type TuneInput,
  type TuneResult,
  type TuneSetting,
} from "./tune";
import type { ManagedTarget } from "./export-formats";

export type BriefContext = {
  input: TuneInput;
  result: TuneResult;
  managed: ManagedTarget;
  localePath: string;
  shareUrl: string;
  exportTab: string;
  confText: string;
};

function settingLines(settings: TuneSetting[]): string {
  return settings
    .map(
      (s) =>
        `- \`${s.key}\` = \`${formatSettingValue(s)}\`${s.restart ? " (restart)" : ""}`,
    )
    .join("\n");
}

function inputBlock(input: TuneInput): string {
  return [
    `- MySQL/MariaDB: ${input.dbVersion}`,
    `- OS: ${input.osType}`,
    `- Profile: ${input.dbType}`,
    `- Host RAM: ${input.totalMemory} ${input.totalMemoryUnit}`,
    `- MySQL RAM share: ${input.mysqlRamPercent ?? 100}%`,
    `- CPU: ${input.cpuNum ?? "(auto)"}`,
    `- max_connections (input): ${input.connectionNum ?? "(auto)"}`,
    `- Storage: ${input.hdType}`,
    `- DB size vs RAM: ${input.dbSize}`,
    `- Role: ${input.serverRole ?? "standalone"}`,
    `- Pooler: ${input.poolerMode ?? "none"}`,
    `- Peak complex queries: ${input.peakComplexQueries ?? 2}`,
  ].join("\n");
}

function warningLines(result: TuneResult): string {
  if (!result.warnings.length) return "- (none)";
  return result.warnings.map((w) => `- [${w.level}] ${w.id}`).join("\n");
}

export function formatHumanBrief(ctx: BriefContext): string {
  const b = ctx.result.budget;
  return `# MySQL tuning brief (human / DBA)

Generated by [mytune](https://mytune.dmosk.net/) in the browser. Treat as a starting point — verify under real load.

## Share link
${ctx.shareUrl}

## Hardware and workload inputs
${inputBlock(ctx.input)}

## Memory budget
- Host RAM: ${formatMemoryKb(b.hostRamKb)}
- MySQL share: ${formatMemoryKb(b.mysqlRamKb)}
- innodb_buffer_pool_size: ${formatMemoryKb(b.bufferPoolKb)}
- tmp tables: ${formatMemoryKb(b.tmpTablesKb)}
- Per-connection buffers × peak: ${formatMemoryKb(b.connectionsWorkMemKb)}
- Remaining for OS/cache: ${formatMemoryKb(b.osCacheKb)}
- Peak risk: ${b.peakRisk ? "yes" : "no"} (factor ${b.peakFactor})

## Recommended settings
${settingLines(ctx.result.settings)}

## Warnings
${warningLines(ctx.result)}

## Managed platform
${ctx.managed}

## Suggested config fragment
\`\`\`
${ctx.confText}
\`\`\`
`;
}

export function formatAgentBrief(ctx: BriefContext): string {
  return `# MySQL tuning brief (AI agent)

Source: mytune browser tool. Do not invent credentials. Apply only after review.

## Goal
Propose and apply a safe MySQL/MariaDB configuration for the described host.

## Constraints
- Prefer incremental changes; restart-required variables need a maintenance window.
- Do not connect to production without explicit operator approval.
- Keep binary log / replica settings aligned with the chosen server role.

## Inputs
${inputBlock(ctx.input)}

## Locale / share
- UI locale path: ${ctx.localePath}
- Share URL: ${ctx.shareUrl}
- Export tab: ${ctx.exportTab}
- Managed target: ${ctx.managed}

## Recommended settings (machine list)
${settingLines(ctx.result.settings)}

## Warnings
${warningLines(ctx.result)}

## Config to apply
\`\`\`ini
${ctx.confText}
\`\`\`

## Suggested agent steps
1. Diff against current \`SHOW VARIABLES\` / my.cnf.
2. Apply dynamic \`SET PERSIST\` values first.
3. Write restart-required keys to my.cnf and schedule restart.
4. Re-check buffer pool hit ratio, tmp disk tables, Innodb_log_waits, Max_used_connections.
`;
}
